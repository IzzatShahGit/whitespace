#!/usr/bin/env bash
# Build the production images and (re)deploy them to the EC2 server behind Caddy.
#
#   make deploy-ec2                 build, upload changed images, migrate, restart
#   SKIP_BUILD=1 make deploy-ec2    reuse the last build (e.g. after an env change)
#   MIGRATE=0 make deploy-ec2       skip database migrations
#
# Needs deploy/ec2/.env.deploy (see .env.deploy.example). The app's production env is
# generated from your local .env plus the production values in that file, so keys added
# locally reach production on the next deploy. Nothing secret is written to the repo.
set -euo pipefail
cd "$(dirname "$0")/.."

CONF=deploy/ec2/.env.deploy
REMOTE=/opt/whitespace
IMAGES=(whitespace-api:prod whitespace-web:prod)

[ -f "$CONF" ] || { echo "Missing $CONF (copy deploy/ec2/.env.deploy.example)" >&2; exit 1; }
[ -f .env ] || { echo "Missing .env (the AI keys etc. are read from it)" >&2; exit 1; }
# shellcheck disable=SC1090
source "$CONF"
: "${EC2_HOST:?set EC2_HOST in $CONF}"
: "${PROD_DATABASE_URL:?set PROD_DATABASE_URL in $CONF}"
: "${PROD_JWT_SECRET:?set PROD_JWT_SECRET in $CONF}"
EC2_KEY="${EC2_KEY:-$HOME/.ssh/whitespace-ec2.pem}"
EC2_KEY="${EC2_KEY/#\~/$HOME}"
DOMAIN="${DOMAIN:-${EC2_HOST//./-}.sslip.io}"

SSH_OPTS=(-i "$EC2_KEY" -o StrictHostKeyChecking=accept-new -o ConnectTimeout=15)
ssh_run() { ssh "${SSH_OPTS[@]}" "ubuntu@$EC2_HOST" "$@"; }

echo "==> Checking the server ($EC2_HOST)"
# On a fresh server, wait for user-data.sh (Docker install) to finish.
ssh_run 'cloud-init status --wait >/dev/null 2>&1 || true; docker compose version >/dev/null' \
  || { echo "Docker is not ready on the server (see: cloud-init status --long)" >&2; exit 1; }

if [ "${SKIP_BUILD:-0}" != 1 ]; then
  scripts/ec2-build.sh
fi

echo "==> Writing production settings"
env_tmp=$(mktemp)
trap 'rm -f "$env_tmp"' EXIT
{
  echo "# Generated by scripts/ec2-deploy.sh from .env + $CONF. Do not edit on the server."
  # Local-only settings and everything overridden below are dropped.
  grep -vE '^[[:space:]]*(#|$)' .env \
    | grep -vE '^(WEB_PORT|API_PORT|DB_PORT|OLLAMA_PORT|OLLAMA_BASE_URL|OLLAMA_MODEL|API_INTERNAL_URL|APP_ENV|LOG_LEVEL|COOKIE_SECURE|PUBLIC_APP_URL|CORS_ORIGINS|DATABASE_URL|JWT_SECRET|TRUSTED_PROXY_HOPS)='
  echo "APP_ENV=production"
  echo "LOG_LEVEL=INFO"
  echo "COOKIE_SECURE=true"
  echo "PUBLIC_APP_URL=https://$DOMAIN"
  echo "CORS_ORIGINS=https://$DOMAIN"
  echo "TRUSTED_PROXY_HOPS=${TRUSTED_PROXY_HOPS:-1}"
  echo "DATABASE_URL=$PROD_DATABASE_URL"
  echo "JWT_SECRET=$PROD_JWT_SECRET"
} > "$env_tmp"

echo "==> Uploading config"
scp -q "${SSH_OPTS[@]}" deploy/ec2/compose.yaml deploy/ec2/Caddyfile "ubuntu@$EC2_HOST:$REMOTE/"
scp -q "${SSH_OPTS[@]}" "$env_tmp" "ubuntu@$EC2_HOST:$REMOTE/.env.prod"
ssh_run "chmod 600 $REMOTE/.env.prod && printf 'DOMAIN=%s\n' '$DOMAIN' > $REMOTE/.env"

# Upload only images the server doesn't already have (same ID = same contents).
for image in "${IMAGES[@]}"; do
  local_id=$(docker image inspect "$image" --format '{{.Id}}')
  remote_id=$(ssh_run "docker image inspect $image --format '{{.Id}}' 2>/dev/null" || true)
  if [ "$local_id" = "$remote_id" ]; then
    echo "==> $image unchanged, not uploading"
  else
    echo "==> Uploading $image"
    docker save "$image" | gzip -1 | ssh_run 'gunzip | docker load'
  fi
done

if [ "${MIGRATE:-1}" = 1 ]; then
  echo "==> Applying database migrations"
  ssh_run "cd $REMOTE && docker compose run --rm --no-deps -w /app/backend api alembic upgrade head"
fi

echo "==> Starting"
ssh_run "cd $REMOTE && docker compose up -d --remove-orphans && docker image prune -f >/dev/null"

# Daily market alerts (replaces a GitHub Actions job: the server is always on).
ssh_run "printf '%s\n' '15 6 * * * cd $REMOTE && docker compose exec -T api python -m whitespace_api.jobs.alerts >> $REMOTE/alerts.log 2>&1' | crontab -"

echo "==> Waiting for https://$DOMAIN"
for _ in $(seq 1 60); do
  if curl -fsS --max-time 5 "https://$DOMAIN/api/v1/health" >/dev/null 2>&1 \
     && curl -fsS --max-time 5 -o /dev/null "https://$DOMAIN/"; then
    echo
    echo "Live: https://$DOMAIN"
    exit 0
  fi
  sleep 3
done
echo "Not answering yet. Logs: ssh -i $EC2_KEY ubuntu@$EC2_HOST 'cd $REMOTE && docker compose logs --tail 80'" >&2
exit 1
